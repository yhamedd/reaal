function toPg(sql: string): string {
  // Replace ? placeholders outside string literals with $1, $2, …
  let n = 0;
  let out = '';
  let quote = false;
  for (const ch of sql) {
    if (ch === "'") quote = !quote;
    out += !quote && ch === '?' ? `$${++n}` : ch;
  }
  return out;
}

function args(params: Params): unknown[] {
  return params.map((v) => (v === undefined ? null : typeof v === 'boolean' ? (v ? 1 : 0) : v));
}

async function pglite(dir: string | null): Promise<DB> {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir) fs.mkdirSync(dir, { recursive: true });
  const pg = new PGlite(dir ?? undefined, { parsers: { 20: Number, 1700: Number } });
  const wrap = (q: { query: typeof pg.query }, inTx: boolean): DB => ({
    inTransaction: inTx,
    async query(sql, params) {
      const r = await q.query(sql, params as any[]);
      return { rows: r.rows as any[], rowCount: r.affectedRows ?? r.rows.length };
    },
    exec: async (text) => {
      await (inTx ? (q as any) : pg).exec(text);
    },
    transaction: (fn) => (inTx ? fn(wrap(q, true)) : pg.transaction((t) => fn(wrap(t as any, true)))),
    close: () => pg.close(),
  });
  return wrap(pg, false);
}

async function postgresUrl(url: string): Promise<DB> {
  const { default: postgres } = await import('postgres');
  const num = { to: 0, from: [20, 1700], serialize: (x: number) => String(x), parse: (x: string) => Number(x) };
  // prepare:false works with Supabase's transaction pooler (port 6543), which serverless functions should use.
  const sql = postgres(url, { prepare: false, max: process.env.VERCEL ? 1 : 10, idle_timeout: 20, types: { num } as any, onnotice: () => undefined });
  const wrap = (q: any, inTx: boolean): DB => ({
    inTransaction: inTx,
    async query(text, params) {
      const r = await q.unsafe(text, params);
      return { rows: [...r], rowCount: r.count ?? r.length };
    },
    exec: async (text) => {
      await q.unsafe(text).simple(); // simple protocol allows several statements
    },
    transaction: (fn) => (inTx ? fn(wrap(q, true)) : sql.begin((t: any) => fn(wrap(t, true))) as Promise<any>),
    close: () => sql.end(),
  });
  return wrap(sql, false);
}

/**
 * Opens the database and applies the schema.
 *  - "postgres://…" / "postgresql://…" → Supabase or another Postgres server
 *  - ":memory:" → throwaway PGlite database (tests)
 *  - anything else → a PGlite data directory on disk (local development)
 */
export async function openDb(target: string): Promise<DB> {
  const db = /^postgres(ql)?:\/\//.test(target) ? await postgresUrl(target) : await pglite(target === ':memory:' ? null : path.resolve(target));
  await migrate(db);
  return db;
}

const SCHEMA_VERSION = crypto.createHash('sha256').update(SCHEMA).digest('hex').slice(0, 16);

/**
 * Applies the schema once per version. Serverless instances may start at the same time, so the
 * work runs in a transaction behind an advisory lock and is skipped when the version matches.
 */
async function migrate(db: DB) {
  const current = async (d: DB) =>
    (await d.query("SELECT to_regclass('schema_meta') IS NOT NULL AS ok", [])).rows[0]?.ok
      ? (await d.query('SELECT version FROM schema_meta LIMIT 1', [])).rows[0]?.version
      : null;
  if ((await current(db)) === SCHEMA_VERSION) return;
  await db.transaction(async (t) => {
    await t.query('SELECT pg_advisory_xact_lock(727274)', []);
    if ((await current(t)) === SCHEMA_VERSION) return;
    await ensureNocase(t);
    await t.exec(SCHEMA);
    // Supabase exposes the public schema through its REST API; with row-level security on and no
    // policies, only the app's own connection (the table owner) can read or write the data.
    await t.exec(
      (await t.query("SELECT tablename FROM pg_tables WHERE schemaname = current_schema()", [])).rows
        .map((r) => `ALTER TABLE "${r.tablename}" ENABLE ROW LEVEL SECURITY;`)
        .join('\n'),
    );
    await t.exec('CREATE TABLE IF NOT EXISTS schema_meta (version TEXT NOT NULL); ALTER TABLE schema_meta ENABLE ROW LEVEL SECURITY; DELETE FROM schema_meta;');
    await t.query('INSERT INTO schema_meta (version) VALUES ($1)', [SCHEMA_VERSION]);
  });
}

/**
 * Case-insensitive comparison and sorting ("Mivida" = "MIVIDA"), used in queries as COLLATE NOCASE.
 * Newer ICU understands "und-u-ks-level2"; some builds only the legacy "@colStrength=secondary".
 */
async function ensureNocase(db: DB) {
  for (const locale of ['und-u-ks-level2', '@colStrength=secondary']) {
    await db.query(`CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = '${locale}', deterministic = false)`, []);
    const ok = (await db.query("SELECT 'Mivida' = 'MIVIDA' COLLATE nocase AS ok", [])).rows[0]?.ok;
    if (ok) return;
    await db.query('DROP COLLATION nocase', []);
  }
  throw new Error('This PostgreSQL server has no ICU support for case-insensitive collations');
}

export async function all<T = any>(db: DB, sql: string, params: Params = []): Promise<T[]> {
  return (await db.query(toPg(sql), args(params))).rows as T[];
}

export async function get<T = any>(db: DB, sql: string, params: Params = []): Promise<T | undefined> {
  return (await all<T>(db, sql, params))[0];
}

/** Runs a write. INSERTs return the new row's id as lastId. */
export async function run(db: DB, sql: string, params: Params = []) {
  let text = toPg(sql);
  const isInsert = /^\s*INSERT\b/i.test(text) && !/\bRETURNING\b/i.test(text);
  if (isInsert) text += ' RETURNING *';
  const r = await db.query(text, args(params));
  return { changes: r.rowCount, lastId: Number(r.rows[0]?.id ?? 0) };
}

/**
 * Inserts many rows with one statement per chunk and returns the new ids in input order.
 * One round trip per 500 rows keeps bulk imports fast against a remote database.
 */
export async function insertMany(db: DB, table: string, cols: string[], rows: unknown[][], opts: { returning?: boolean; onConflictDoNothing?: boolean; chunk?: number } = {}) {
  const ids: number[] = [];
  const size = opts.chunk ?? Math.max(1, Math.min(500, Math.floor(60000 / Math.max(1, cols.length))));
  for (let i = 0; i < rows.length; i += size) {
    const part = rows.slice(i, i + size);
    const values = part.map(() => `(${cols.map(() => '?').join(', ')})`).join(', ');
    const sql = `INSERT INTO ${table} (${cols.join(', ')}) VALUES ${values}${opts.onConflictDoNothing ? ' ON CONFLICT DO NOTHING' : ''}${opts.returning ? ' RETURNING id' : ''}`;
    const r = await db.query(toPg(sql), args(part.flat()));
    if (opts.returning) ids.push(...r.rows.map((x) => Number(x.id)));
  }
  return ids;
}

/** Runs fn inside one transaction; nested calls reuse the outer transaction. */
export async function tx<T>(db: DB, fn: (db: DB) => Promise<T>): Promise<T> {
  return db.inTransaction ? fn(db) : db.transaction(fn);
}

export function nowIso(): string {
  return new Date().toISOString().replace('T', ' ').slice(0, 19);
}

