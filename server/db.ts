/**
 * Database handle. Works on PostgreSQL through either driver:
 *  - Supabase (or any Postgres) via the `postgres` package when DATABASE_URL is set
 *  - PGlite (Postgres compiled to WebAssembly) for local development and tests
 * Queries use `?` placeholders; they're converted to $1, $2… here.
 */
export interface DB {
  query(sql: string, params: unknown[]): Promise<{ rows: any[]; rowCount: number }>;
  /** Runs a multi-statement script without parameters (schema). */
  exec(sql: string): Promise<void>;
  transaction<T>(fn: (db: DB) => Promise<T>): Promise<T>;
  close(): Promise<void>;
  inTransaction?: boolean;
}
export type Params = unknown[];

